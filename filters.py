# -*- coding: utf-8 -*-
"""
STT 후처리 필터 규칙 (별도 파일 관리)
- 이 파일만 수정하면 정규식 규칙 추가/삭제 가능
- (정규식 패턴, 치환 문자열) 순서대로 적용됩니다.
"""

import re
from typing import List, Tuple

# (pattern, replacement) 목록. 아래에 규칙을 추가하세요.
RULES: List[Tuple[str, str]] = [
    # 1. "10, C, 30분" → "10시 30분" (쉼표로 분리된 숫자 + C/씨 + 분)
    (r'(\d+)\s*,\s*[CcＣｃ씨]\s*,?\s*(\d+)\s*분', r'\1시 \2분'),
    # 2. "10 C 30분" → "10시 30분" (공백으로 분리)
    (r'(\d+)\s+[CcＣｃ씨]\s+(\d+)\s*분', r'\1시 \2분'),
    # 3. "10하는 시인 30분" / "10하는 시은 56분" → "10시 30분" (잘못 인식된 '시')
    (r'(\d+)\s*하는\s*시\s*인\s*(\d+)\s*분', r'\1시 \2분'),
    (r'(\d+)\s*하는\s*시인\s*(\d+)\s*분', r'\1시 \2분'),
    (r'(\d+)하는\s*시인\s*(\d+)\s*분', r'\1시 \2분'),
    (r'(\d+)\s*하는\s*시은\s*(\d+)\s*분', r'\1시 \2분'),   # "10하는 시은 56분" → "10시 56분"
    (r'(\d+)하는\s*시은\s*(\d+)\s*분', r'\1시 \2분'),       # 붙어있는 경우
    (r'(\d+)\s*하는\s*시인?\s*(\d+)\s*분', r'\1시 \2분'),
    (r'(\d+)\s*[하는]*\s*시인?\s+(\d+)\s*분', r'\1시 \2분'),
    (r'(\d+)\s*[하는]*\s*시은\s*(\d+)\s*분', r'\1시 \2분'), # "시은" 변형
    # 4. "5,6분" → "56분" (쉼표로 잘못 분리된 숫자)
    (r'(\d+)\s*,\s*(\d+)\s*분', r'\1\2분'),
    # 5. "10 시 30 분" → "10시 30분" (띄어쓰기 정리)
    (r'(\d+)\s+시\s+(\d+)\s+분', r'\1시 \2분'),
    # 6. "지금 시각은 10 하는 시인 56 분" → "지금 시각은 10시 56분"
    (r'(\d+)\s+하는\s+시인\s+(\d+)\s*분', r'\1시 \2분'),
    # 7. "12시 반" → "12시 30분" (반 = 30분)
    (r'(\d+)\s*시\s*반(?!\w)', r'\1시 30분'),
    # 8. 숫자 + "시" 만 있는 경우 ("10 시" → "10시")
    (r'(\d+)\s+시(?!\w)', r'\1시'),
    # 9. "분" 앞 숫자 정리 ("30 분" → "30분")
    (r'(\d+)\s+분(?!\w)', r'\1분'),
]


def apply_filters(text: str) -> str:
    """
    STT 결과 텍스트에 후처리 규칙을 순서대로 적용합니다.
    규칙 적용 중 예외가 나면 해당 규칙만 건너뛰고 원문 유지.
    """
    if not text or not isinstance(text, str):
        return text or ""
    result = text
    for pattern, replacement in RULES:
        try:
            result = re.sub(pattern, replacement, result)
        except Exception:
            continue
    return result
